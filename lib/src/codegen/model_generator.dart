/// Turns WordPress REST API JSON schemas (the `schema` of an `OPTIONS`
/// answer) into Dart model classes for `client.resource<T>()`.
///
/// Used by `dart run wordpress_client:generate`. Every field is nullable,
/// because WordPress leaves fields out depending on `context` and
/// `_fields`; values are converted leniently and the whole JSON stays
/// available as `self`.
library;

/// One model to generate: [className] from [schema].
final class ModelSource {
  const ModelSource({
    required this.className,
    required this.schema,
    this.route,
  });

  final String className;
  final Map<String, dynamic> schema;

  /// The route the schema came from, for the doc comment.
  final String? route;
}

/// Generates the source of one Dart file holding every model in [models].
String generateModels(List<ModelSource> models, {String? origin}) {
  final classes = <String>[];
  for (final model in models) {
    _ClassWriter(
      model.className,
      _properties(model.schema),
      classes,
      doc: [
        if (model.schema['title'] case final String title) '`$title`',
        if (model.route != null) 'from `${model.route}`',
      ].join(' '),
    ).write();
  }

  return [
    '// Generated by `dart run wordpress_client:generate`${origin == null ? '' : ' from $origin'}.',
    '// Re-running the generator overwrites this file.',
    '',
    '// ignore_for_file: type=lint',
    '',
    "import 'package:wordpress_client/wordpress_client.dart' show ISelfRepresentative;",
    '',
    ...classes,
    _helpers,
  ].join('\n');
}

/// A class name from a schema title: `wp_block` becomes `WpBlock`.
String classNameFor(String title) {
  final name = _pascal(title);

  return name.isEmpty ? 'Model' : name;
}

Map<String, Map<String, dynamic>> _properties(Map<String, dynamic> schema) {
  final properties = schema['properties'];
  if (properties is! Map) {
    return const {};
  }

  return {
    for (final MapEntry(:key, :value) in properties.entries)
      if (value is Map) '$key': value.cast<String, dynamic>(),
  };
}

final class _ClassWriter {
  _ClassWriter(this.name, this.properties, this.out, {this.doc = ''});

  final String name;
  final Map<String, Map<String, dynamic>> properties;
  final List<String> out;
  final String doc;

  void write() {
    final fields = <_Field>[];
    final used = <String>{'self'};

    for (final MapEntry(key: json, value: schema) in properties.entries) {
      final base = _fieldName(json);
      var field = base;
      for (var n = 2; !used.add(field); n++) {
        field = '$base$n';
      }
      fields.add(_Field(json, field, _type(json, schema), schema));
    }

    final b = StringBuffer()
      ..writeln(doc.isEmpty ? '/// A $name.' : '/// $doc.')
      ..writeln('final class $name implements ISelfRepresentative {')
      ..writeln('  const $name({');
    for (final f in fields) {
      b.writeln('    this.${f.name},');
    }
    b
      ..writeln('    this.self = const {},')
      ..writeln('  });')
      ..writeln()
      ..writeln('  factory $name.fromJson(Map<String, dynamic> json) {')
      ..writeln('    return $name(');
    for (final f in fields) {
      final value = f.type.decode("json['${_escape(f.json)}']");
      b.writeln('      ${f.name}: $value,');
    }
    b
      ..writeln('      self: json,')
      ..writeln('    );')
      ..writeln('  }')
      ..writeln();

    for (final f in fields) {
      final description = f.schema['description'];
      if (description is String && description.trim().isNotEmpty) {
        b.writeln('  /// ${description.trim().replaceAll('\n', ' ')}');
      }
      if (f.schema['readonly'] == true) {
        b.writeln('  ///');
        b.writeln('  /// Read only.');
      }
      b.writeln('  final ${f.type.dart}? ${f.name};');
      b.writeln();
    }

    b
      ..writeln('  @override')
      ..writeln('  final Map<String, dynamic> self;')
      ..writeln()
      ..writeln('  /// The fields that are set, as JSON for create and update.')
      ..writeln('  Map<String, dynamic> toJson() {')
      ..writeln('    return <String, dynamic>{');
    for (final f in fields) {
      b.writeln("      '${_escape(f.json)}': ${f.type.encode(f.name)},");
    }
    b
      ..writeln('    }..removeWhere((_, value) => value == null);')
      ..writeln('  }')
      ..writeln('}');

    out.add(b.toString());
  }

  _Type _type(String json, Map<String, dynamic> schema) {
    final type = _primaryType(schema['type']);

    switch (type) {
      case 'integer':
        return const _Type.simple('int', '_int');
      case 'number':
        return const _Type.simple('double', '_double');
      case 'boolean':
        return const _Type.simple('bool', '_bool');
      case 'string':
        return schema['format'] == 'date-time'
            ? const _Type.date()
            : const _Type.simple('String', '_string');
      case 'array':
        final items = schema['items'];
        final item = items is Map
            ? _type(json, items.cast<String, dynamic>())
            : const _Type.dynamic();
        return _Type.list(item);
      case 'object':
        final nested = _properties(schema);
        if (nested.isEmpty) {
          return const _Type.map();
        }
        final nestedName = '$name${_pascal(json)}';
        _ClassWriter(
          nestedName,
          nested,
          out,
          doc: 'The `$json` field of [$name]',
        ).write();
        return _Type.object(nestedName);
      default:
        return const _Type.dynamic();
    }
  }
}

/// The single non-null type of a schema `type` (`["string", "null"]` reads
/// as `string`), or null when there are several or none.
String? _primaryType(Object? type) {
  if (type is String) {
    return type;
  }
  if (type is List) {
    final real = type.where((t) => t != 'null').toSet();
    return real.length == 1 ? '${real.single}' : null;
  }
  return null;
}

final class _Field {
  _Field(this.json, this.name, this.type, this.schema);

  final String json;
  final String name;
  final _Type type;
  final Map<String, dynamic> schema;
}

final class _Type {
  const _Type.simple(this.dart, this._converter)
      : _kind = _Kind.simple,
        _item = null;
  const _Type.date()
      : dart = 'DateTime',
        _converter = '_date',
        _kind = _Kind.date,
        _item = null;
  const _Type.map()
      : dart = 'Map<String, dynamic>',
        _converter = '_map',
        _kind = _Kind.simple,
        _item = null;
  const _Type.dynamic()
      : dart = 'Object',
        _converter = null,
        _kind = _Kind.simple,
        _item = null;
  _Type.object(String className)
      : dart = className,
        _converter = '$className.fromJson',
        _kind = _Kind.object,
        _item = null;
  _Type.list(_Type item)
      : dart = 'List<${item.dart}>',
        _converter = null,
        _kind = _Kind.list,
        _item = item;

  final String dart;
  final String? _converter;
  final _Kind _kind;
  final _Type? _item;

  String decode(String value) {
    return switch (_kind) {
      _Kind.object => '_object($value, $_converter)',
      _Kind.list => '_list($value, (e) => ${_item!.decode('e')})',
      _ => _converter == null ? value : '$_converter($value)',
    };
  }

  String encode(String value) {
    return switch (_kind) {
      _Kind.date => '$value?.toIso8601String()',
      _Kind.object => '$value?.toJson()',
      _Kind.list when _item!._kind != _Kind.simple =>
        '$value?.map((e) => ${_item!.encode('e').replaceAll('e?.', 'e.')}).toList()',
      _ => value,
    };
  }
}

enum _Kind { simple, date, object, list }

const _reserved = {
  'abstract', 'as', 'assert', 'async', 'await', 'base', 'break', 'case', //
  'catch', 'class', 'const', 'continue', 'covariant', 'default', 'deferred',
  'do', 'dynamic', 'else', 'enum', 'export', 'extends', 'extension',
  'external', 'factory', 'false', 'final', 'finally', 'for', 'function',
  'get', 'hide', 'if', 'implements', 'import', 'in', 'interface', 'is',
  'late', 'library', 'mixin', 'new', 'null', 'of', 'on', 'operator', 'part',
  'required', 'rethrow', 'return', 'sealed', 'set', 'show', 'static',
  'super', 'switch', 'sync', 'this', 'throw', 'true', 'try', 'type',
  'typedef', 'var', 'void', 'when', 'while', 'with', 'yield', 'toJson',
  'hashCode', 'runtimeType', 'toString', 'noSuchMethod',
};

String _fieldName(String json) {
  final words = _words(json);
  if (words.isEmpty) {
    return 'field';
  }

  final first = words.first;
  final head = first == first.toUpperCase()
      ? first.toLowerCase()
      : first[0].toLowerCase() + first.substring(1);
  var name = head + words.skip(1).map(_capitalize).join();
  if (RegExp('^[0-9]').hasMatch(name)) {
    name = 'value$name';
  }

  return _reserved.contains(name) ? '${name}Value' : name;
}

String _pascal(String text) => _words(text).map(_capitalize).join();

List<String> _words(String text) =>
    text.split(RegExp('[^A-Za-z0-9]+')).where((w) => w.isNotEmpty).toList();

String _capitalize(String word) => word[0].toUpperCase() + word.substring(1);

String _escape(String json) =>
    json.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$');

const _helpers = r'''
int? _int(Object? value) =>
    value is num ? value.toInt() : int.tryParse('${value ?? ''}');

double? _double(Object? value) =>
    value is num ? value.toDouble() : double.tryParse('${value ?? ''}');

bool? _bool(Object? value) => switch (value) {
      final bool b => b,
      1 || '1' || 'true' => true,
      0 || '0' || 'false' => false,
      _ => null,
    };

String? _string(Object? value) =>
    value is String ? value : (value is num || value is bool ? '$value' : null);

DateTime? _date(Object? value) =>
    value is String && value.isNotEmpty ? DateTime.tryParse(value) : null;

Map<String, dynamic>? _map(Object? value) =>
    value is Map ? value.cast<String, dynamic>() : null;

T? _object<T>(Object? value, T Function(Map<String, dynamic> json) fromJson) =>
    value is Map ? fromJson(value.cast<String, dynamic>()) : null;

List<T>? _list<T>(Object? value, T? Function(Object? item) convert) {
  if (value is! List) {
    return null;
  }

  return [
    for (final item in value)
      if (convert(item) case final converted?) converted,
  ];
}
''';
